const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const policy = {};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../devialet/hero/ReaderPolicy.js'), 'utf8').replace('.pragma library', ''), policy);
const t = { anilist_id: 21507, episode: 3, lang: 'vo' };
const r = { source: 'voiranime', reader_id: 'a'.repeat(64), supported: true };
const attempt = { ...r, code: 'source_denied' };
const failures = policy.remember({}, t, [attempt], 1000);
assert.equal(policy.usable(r, t, failures, 1001), false);
assert.equal(policy.usable(r, { ...t, episode: 4 }, failures, 1001), true);
assert.equal(policy.usable(r, { ...t, lang: 'vf' }, failures, 1001), true);
assert.equal(policy.usable(r, t, failures, 61001), true);
assert.equal(policy.usable(r, t, failures, 1001, { source: r.source, readerId: r.reader_id }), true);
assert.equal(policy.usable({ ...r, supported: false }, t, {}, 1001), false);
assert.equal(policy.usable(r, t, policy.recovered(failures, t, r.source, r.reader_id), 1001), true);
assert.equal(Object.keys(policy.remember({}, t, [{ ...attempt, code: 'reader_timeout' }], 1000)).length, 0);
assert.equal(Object.keys(policy.remember({}, t, [{ ...attempt, reader_id: 'bad' }], 1000)).length, 0);
assert.equal(policy.bitrate(3200), 'Débit annoncé · 3,2 Mb/s');
for (const bad of [null, undefined, 0, -1, NaN, Infinity, '3200']) assert.equal(policy.bitrate(bad), '');
console.log('Reader policy: scoped failures, expiry, recovery, active reader and bitrate pass.');
